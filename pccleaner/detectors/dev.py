PKG_REC = ("Seguro. Pacotes são baixados de novo quando necessário (instalações futuras podem ficar "
           "mais lentas ou exigir internet). Prefira o comando oficial: {cmd}")


def _safe_pkg(id: str, name: str, app: str, paths: list[str], cmd: str = "", reason: str = "") -> Rule:
    return rule(id, name, DC, app, S,
                reason or f"Cache de downloads do {app}. Não afeta projetos ou ambientes já instalados.",
                PKG_REC.format(cmd=cmd) if cmd else "", CONTENTS, paths, command_hint=cmd)


